"""SMTP Email notification dispatcher for high-priority security incidents."""

import logging
import smtplib
from datetime import datetime, timezone
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Any

from ..config import settings

logger = logging.getLogger(__name__)


def send_email_alert(
    subject: str,
    message: str,
    severity: str = "CRITICAL",
    details: dict[str, Any] | None = None,
) -> bool:
    """Send an incident email alert via SMTP."""
    smtp_server = settings.SMTP_SERVER
    smtp_port = settings.SMTP_PORT
    smtp_user = settings.SMTP_USER
    smtp_password = settings.SMTP_PASSWORD
    recipient = settings.ALERT_EMAIL_TO

    if not smtp_user or not smtp_password or not recipient:
        logger.debug("Email alert skipped: SMTP credentials or recipient not configured.")
        return False

    msg = MIMEMultipart("alternative")
    msg["Subject"] = f"[{severity.upper()}] SOAR Lite Security Alert: {subject}"
    msg["From"] = smtp_user
    msg["To"] = recipient

    # HTML Body
    details_html = ""
    if details:
        details_html = "<h3>Incident Context</h3><ul>"
        for k, v in details.items():
            details_html += f"<li><b>{k}:</b> <code>{v}</code></li>"
        details_html += "</ul>"

    color = "#dc3545" if severity.upper() == "CRITICAL" else "#fd7e14"
    html_content = f"""
    <html>
      <body style="font-family: Arial, sans-serif; background: #0f172a; color: #f8fafc; padding: 20px;">
        <div style="max-width: 600px; margin: auto; background: #1e293b; border-radius: 8px; border: 1px solid #334155; padding: 24px;">
          <h2 style="color: {color}; margin-top: 0;">🛡️ SOAR Lite Security Alert</h2>
          <p><b>Severity:</b> <span style="background: {color}; color: white; padding: 3px 8px; border-radius: 4px; font-weight: bold;">{severity.upper()}</span></p>
          <p><b>Subject:</b> {subject}</p>
          <p><b>Details:</b> {message}</p>
          <p><b>Timestamp:</b> {datetime.now(timezone.utc).isoformat()}</p>
          {details_html}
          <hr style="border: 0; border-top: 1px solid #334155; margin: 20px 0;" />
          <p style="font-size: 12px; color: #94a3b8;">Automated alert generated by SOAR Lite Endpoint Protection.</p>
        </div>
      </body>
    </html>
    """

    msg.attach(MIMEText(message, "plain"))
    msg.attach(MIMEText(html_content, "html"))

    try:
        with smtplib.SMTP(smtp_server, smtp_port, timeout=5.0) as server:
            server.starttls()
            server.login(smtp_user, smtp_password)
            server.sendmail(smtp_user, [recipient], msg.as_string())
            logger.info("Email incident alert sent successfully to %s", recipient)
            return True
    except Exception as exc:
        logger.warning("Failed to send SMTP email alert: %s", exc)
        return False
